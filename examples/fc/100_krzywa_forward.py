"""### NORMALIZACJA WSPÓŁCZYNNIKÓW Q vs Y
Problem: surowe współczynniki Q/Y nie muszą dawać średniej ważonej = 1.0

Rozwiązanie: normalizujemy je tak, aby suma(Q_i * godziny_i) / suma(godziny) = 1.0

Dzięki temu: cena_roku = suma(cena_kwartału_i * godziny_i) / suma(godziny)

"""

def normalize_ratios(ratios, hours):
    weighted_sum = sum(r * h for r, h in zip(ratios, hours))
    total_hours = sum(hours)
    current_weighted_avg = weighted_sum / total_hours
    normalization_factor = 1.0 / current_weighted_avg
    return [r * normalization_factor for r in ratios]

raw_ratios = qvsy_estimates['QvsY'].tolist()
