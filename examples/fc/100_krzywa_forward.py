"""### FUNKCJA WYCENY KONTRAKTU
Wycena dowolnego okresu (np. M1-M6, Q2, H1 itp.)
Wzór: cena_kontraktu = suma(cena_miesiąca × godziny) / suma(godziny)
Jest to średnia ważona cen miesięcznych, gdzie wagą jest liczba godzin.
"""

def wycena_kontraktu(start_month, end_month, forward_curve_df):
    """
    Wycena kontraktu od start_month do end_month (włącznie).

    Parametry:
    - start_month: int (1-12)
    - end_month: int (1-12)
    - forward_curve_df: DataFrame z kolumnami 'month_num', 'month_price', 'hours'

    Zwraca:
    - średnią ważoną cenę kontraktu
    """
    contract_months = forward_curve_df[
        (forward_curve_df['date'] >= start_month) &
        (forward_curve_df['date'] <= end_month)
    ].copy()

    if contract_months.empty:
        return None, None

    total_value = (contract_months['month_price'] * contract_months['hours']).sum()
    total_hours = contract_months['hours'].sum()
    avg_price = total_value / total_hours

    return avg_price, contract_months

